# Day 1 - 30 Days of Python Challenge

# 1. Arithmetic Operations
print(2 + 3)  # Addition
print(3 - 1)  # Subtraction
print(2 * 3)  # Multiplication
print(3 / 2)  # Division
print(3 ** 2) # Exponentiation
print(3 % 2)  # Modulus
print(3 // 2) # Floor division

# 2. Strings
print("AMAR SALEM")  # String
print("NASER MOHAMED NUR")  # String
print("Eritrea")  # String
print("I am enjoying 30 days of python")  # String

# 3. Data Types
print(type(10))                  # Int
print(type(9.8))                # Float
print(type(1 + 3j))              # Complex
print(type('Amar'))          # String
print(type([1, 2, 3]))           # List
print(type({'name': 'Amar'}))  # Dictionary
print(type((9.8, 3.14, 2.7)))    # Tuple
print(type({9.8, 3.14, 2.7}))    # Set

# 4. Euclidean distance 
x1, y1 = 2, 3
x2, y2 = 10, 8
distance = ((x2 - x1) ** 2 + (y2 - y1) ** 2) ** 0.5 # Using exponentiation ** 0.5 for square root
print(distance) # Output: ~9.434